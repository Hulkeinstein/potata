import { fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { AdminProductCatalogClient } from "./AdminProductCatalogClient";
const mocks = vi.hoisted(() => ({ refresh: vi.fn(), params: "quality=missing-any" }));
vi.mock("next/navigation", () => ({ useRouter: () => ({ refresh: mocks.refresh }), useSearchParams: () => new URLSearchParams(mocks.params) }));
const items = ["One", "Two"].map((name, i) => ({ id: `p${i}`, name, brand: "QA", price: 10, imageUrl: "/a.png", isActive: true, category: "Top", variants: [{ stock: i, isManuallySoldOut: true }] }));
const data = { items, total: 2, page: 1, pageSize: 20 };
afterEach(() => { vi.unstubAllGlobals(); vi.clearAllMocks(); mocks.params = "quality=missing-any"; });
describe("bulk visibility workflow", () => {
  it("requires confirmation and cancellation never writes", () => {
    const fetcher = vi.fn(); vi.stubGlobal("fetch", fetcher);
    render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("현재 페이지 전체 선택"));
    fireEvent.click(screen.getByRole("button", { name: "선택 상품 판매 중지" }));
    const dialog = screen.getByRole("dialog");
    expect(within(dialog).getByText("One")).toBeTruthy();
    expect(within(dialog).getByText("Two")).toBeTruthy();
    expect(fetcher).not.toHaveBeenCalled();
    fireEvent.click(within(dialog).getByRole("button", { name: "취소" }));
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(fetcher).not.toHaveBeenCalled();
  });
  it("sends only selected IDs and target then clears selection on success", async () => {
    const fetcher = vi.fn().mockResolvedValue(new Response(JSON.stringify({ success: true, processed: 1 })));
    vi.stubGlobal("fetch", fetcher);
    render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("One 선택"));
    fireEvent.click(screen.getByRole("button", { name: "선택 상품 재노출" }));
    fireEvent.click(within(screen.getByRole("dialog")).getByRole("button", { name: "재노출 실행" }));
    await waitFor(() => expect(mocks.refresh).toHaveBeenCalled());
    expect(fetcher.mock.calls[0]?.[0]).toBe("/api/admin/catalog/status");
    expect(JSON.parse(fetcher.mock.calls[0]?.[1].body)).toEqual({ ids: ["p0"], isActive: true });
    expect(screen.getByText("선택 0개")).toBeTruthy();
  });
  it("keeps selection after a network failure and explains unknown outcome", async () => {
    vi.stubGlobal("fetch", vi.fn().mockRejectedValue(new TypeError("offline")));
    render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("현재 페이지 전체 선택"));
    fireEvent.click(screen.getByRole("button", { name: "선택 상품 판매 중지" }));
    fireEvent.click(within(screen.getByRole("dialog")).getByRole("button", { name: "판매 중지 실행" }));
    await waitFor(() => expect(screen.getByRole("alert").textContent).toContain("새로고침"));
    expect(screen.getByText("선택 2개")).toBeTruthy();
  });
  it("clears selection and confirmation when query or visible snapshots change", () => {
    const { rerender } = render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("One 선택"));
    fireEvent.click(screen.getByRole("button", { name: "선택 상품 판매 중지" }));
    rerender(<AdminProductCatalogClient initialData={{ ...data, items: items.map((item) => ({ ...item, isActive: false })) }} />);
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(screen.getByText("선택 0개")).toBeTruthy();
    fireEvent.click(screen.getByLabelText("One 선택"));
    mocks.params = "page=2";
    rerender(<AdminProductCatalogClient initialData={data} />);
    expect(screen.getByText("선택 0개")).toBeTruthy();
  });
  it("supports Escape and focus restoration without writing", () => {
    const fetcher = vi.fn(); vi.stubGlobal("fetch", fetcher);
    render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("One 선택"));
    const trigger = screen.getByRole("button", { name: "선택 상품 판매 중지" });
    trigger.focus();
    fireEvent.click(trigger);
    const dialog = screen.getByRole("dialog");
    const cancel = within(dialog).getByRole("button", { name: "취소" });
    const confirm = within(dialog).getByRole("button", { name: "판매 중지 실행" });
    expect(document.activeElement).toBe(cancel);
    fireEvent.keyDown(cancel, { key: "Tab", shiftKey: true });
    expect(document.activeElement).toBe(confirm);
    fireEvent.keyDown(confirm, { key: "Tab" });
    expect(document.activeElement).toBe(cancel);
    fireEvent.keyDown(cancel, { key: "Escape" });
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(document.activeElement).toBe(trigger);
    expect(fetcher).not.toHaveBeenCalled();
  });
  it("locks confirmation and individual controls until the request settles", async () => {
    let resolveRequest: ((value: Response) => void) | undefined;
    const fetcher = vi.fn(() => new Promise<Response>((resolve) => { resolveRequest = resolve; }));
    vi.stubGlobal("fetch", fetcher);
    render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("현재 페이지 전체 선택"));
    fireEvent.click(screen.getByRole("button", { name: "선택 상품 판매 중지" }));
    const confirm = within(screen.getByRole("dialog")).getByRole("button", { name: "판매 중지 실행" });
    fireEvent.click(confirm);
    fireEvent.click(confirm);
    expect(fetcher).toHaveBeenCalledTimes(1);
    expect(screen.getByLabelText("One 선택").hasAttribute("disabled")).toBe(true);
    expect(screen.getAllByRole("button", { name: "판매 중지" }).every((button) => button.hasAttribute("disabled"))).toBe(true);
    resolveRequest?.(new Response(JSON.stringify({ success: true, processed: 2 })));
    await waitFor(() => expect(mocks.refresh).toHaveBeenCalled());
  });
  it("disables bulk actions when there are no visible products", () => {
    render(<AdminProductCatalogClient initialData={{ ...data, items: [], total: 0 }} />);
    expect(screen.getByLabelText("현재 페이지 전체 선택").hasAttribute("disabled")).toBe(true);
    expect(screen.getByRole("button", { name: "선택 상품 판매 중지" }).hasAttribute("disabled")).toBe(true);
  });
  it("preserves applied-count and cache warning when refreshed product status resets selection", async () => {
    vi.stubGlobal("fetch", vi.fn().mockResolvedValue(new Response(JSON.stringify({ success: true, processed: 1, warning: "고객 화면 갱신 지연" }))));
    const { rerender } = render(<AdminProductCatalogClient initialData={data} />);
    fireEvent.click(screen.getByLabelText("One 선택"));
    fireEvent.click(screen.getByRole("button", { name: "선택 상품 판매 중지" }));
    fireEvent.click(within(screen.getByRole("dialog")).getByRole("button", { name: "판매 중지 실행" }));
    await waitFor(() => expect(mocks.refresh).toHaveBeenCalled());
    rerender(<AdminProductCatalogClient initialData={{ ...data, items: items.map((item) => ({ ...item, isActive: false })) }} />);
    expect(screen.getByRole("status").textContent).toContain("상품 1개 처리 완료");
    expect(screen.getByRole("status").textContent).toContain("고객 화면 갱신 지연");
    expect(screen.getByText("선택 0개")).toBeTruthy();
  });
});
